// Package diagnostic calcule, par commit, les données des signaux de diagnostic (phase 7, voir
// documentation/fr/12-supervision-diagnostic.md) : lignes et fichiers après exclusion, outils d'IA
// déclarés dans le message (signaux D1 et D2), auteur bot (D3), fichier de configuration d'agent (D4).
//
// Un signal n'est jamais un verdict : ce paquet ne décide rien, il ne fait que mesurer. Il ne garde
// rien du message de commit ni des chemins de fichiers : seuls des compteurs, des booléens et des
// identifiants d'outils sortent de Compute. Comme le reste du cœur métier, il n'écrit aucun log.
//
// Références : signaux et listes de la spécification « Détection des signaux de production de code
// assistée par IA » v0.2, sections 3.2 et 4.1 ; heuristiques par fichiers, trailers et auteurs de
// Robbes et al. (2026, arXiv:2601.18341) ; signatures par agent de Ghaleb (MSR 2026, arXiv:2601.17406).
package diagnostic

import (
	"regexp"
	"slices"
)

// Identifiants d'outils, écrits dans commit_signals.tool_ids. Stables : ils font partie des données
// de l'espace (une valeur ne change jamais de sens ; un nouvel outil reçoit un nouvel identifiant).
const (
	ToolClaude  = "claude"
	ToolCopilot = "copilot"
	ToolCodex   = "codex"
	ToolCursor  = "cursor"
	// ToolUnnamed : signature d'IA reconnue sans outil nommé (« 🤖 Generated … »).
	ToolUnnamed = "unnamed"
)

// agentBranchPrefixes (signal D5) sont les préfixes de branches créées par des agents de codage
// (spécification, section 4.1).
var agentBranchPrefixes = []struct{ prefix, tool string }{
	{"codex/", ToolCodex},
	{"copilot/", ToolCopilot},
	{"claude/", ToolClaude},
	{"cursor/", ToolCursor},
}

// toolPattern associe une expression régulière à un identifiant d'outil.
type toolPattern struct {
	tool string
	re   *regexp.Regexp
}

// coAuthorPatterns (signal D1) s'appliquent à la valeur d'un trailer « Co-authored-by: » (nom et
// e-mail). Liste indicative de la spécification, section 4.1, à maintenir :
//
//	Co-authored-by: Claude <noreply@anthropic.com>
//	Co-authored-by: Copilot <copilot@github.com>
//	Co-authored-by: Codex.*<noreply@openai.com>
//	Co-authored-by: Cursor.*
var coAuthorPatterns = []toolPattern{
	// Claude est aussi un prénom : seule l'adresse d'Anthropic compte, jamais le nom seul.
	{ToolClaude, regexp.MustCompile(`(?i)<noreply@anthropic\.com>`)},
	{ToolCopilot, regexp.MustCompile(`(?i)^copilot\b|<copilot@github\.com>`)},
	{ToolCodex, regexp.MustCompile(`(?i)^codex\b|<noreply@openai\.com>`)},
	{ToolCursor, regexp.MustCompile(`(?i)^cursor\b|@cursor\.com>`)},
}

// signaturePatterns (signal D2, partie message de commit) s'appliquent à chaque ligne du message.
// La partie « description de pull request » du signal D2 vient en phase 7.2.
var signaturePatterns = []toolPattern{
	{ToolClaude, regexp.MustCompile(`(?i)generated with \[?claude code\]?`)},
	{ToolCodex, regexp.MustCompile(`(?i)generated by codex`)},
	{ToolUnnamed, regexp.MustCompile(`(?i)🤖\s*generated\b`)},
}

// coAuthorTrailer reconnaît une ligne de trailer « Co-authored-by: valeur » (casse ignorée).
var coAuthorTrailer = regexp.MustCompile(`(?i)^\s*co-authored-by:\s*(.+?)\s*$`)

// botLogins (signal D3) sont des comptes bot connus, en minuscules, en plus de tout nom ou login
// terminé par « [bot] ».
var botLogins = map[string]bool{
	"copilot-swe-agent": true,
}

// agentConfigNames (signal D4) sont les noms de fichiers de configuration d'agent (dernier élément
// du chemin, casse respectée) ; agentConfigPrefixes, des préfixes de nom (« .aider.conf.yml ») ;
// agentConfigPaths, des chemins complets ; agentConfigDirs, des répertoires (n'importe où dans le
// chemin).
var (
	agentConfigNames    = map[string]bool{"AGENTS.md": true, "CLAUDE.md": true, ".cursorrules": true, ".windsurfrules": true}
	agentConfigPrefixes = []string{".aider"}
	agentConfigPaths    = map[string]bool{".github/copilot-instructions.md": true}
	agentConfigDirs     = []string{".cursor"}
)

// DefaultExclude est la liste par défaut du réglage diagnostic.exclude (spécification, section 3.2) :
// fichiers de verrouillage, dépendances embarquées, fichiers générés, instantanés de tests. Les
// fichiers binaires sont toujours exclus, sans motif. Syntaxe : voir Excluder.
var DefaultExclude = []string{
	"package-lock.json", "yarn.lock", "pnpm-lock.yaml", "go.sum", "poetry.lock", "Cargo.lock",
	"composer.lock", "Gemfile.lock",
	"vendor/", "node_modules/", "third_party/",
	"*.pb.go", "*_generated.*", "*.min.js", "dist/", "build/",
	"__snapshots__/", "*.snap",
}

// AgentConfigPathspecs renvoie les pathspecs Git (magie « glob » et « literal ») des fichiers de
// configuration d'agent du signal D4, n'importe où dans le dépôt : mêmes règles qu'isAgentConfig.
// Sert à dater le premier ajout d'un tel fichier sur un clone (contexte D4).
func AgentConfigPathspecs() []string {
	var out []string
	names := make([]string, 0, len(agentConfigNames))
	for n := range agentConfigNames {
		names = append(names, n)
	}
	slices.Sort(names)
	for _, n := range names {
		out = append(out, ":(glob)"+n, ":(glob)**/"+n)
	}
	for _, prefix := range agentConfigPrefixes {
		out = append(out, ":(glob)"+prefix+"*", ":(glob)**/"+prefix+"*")
	}
	paths := make([]string, 0, len(agentConfigPaths))
	for p := range agentConfigPaths {
		paths = append(paths, p)
	}
	slices.Sort(paths)
	for _, p := range paths {
		out = append(out, ":(literal)"+p)
	}
	for _, d := range agentConfigDirs {
		out = append(out, ":(glob)"+d+"/**", ":(glob)**/"+d+"/**")
	}
	return out
}
