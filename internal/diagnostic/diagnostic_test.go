func TestCompute(t *testing.T) {
	ex, err := NewExcluder(DefaultExclude)
	if err != nil {
		t.Fatal(err)
	}
	in := Input{
		Message:    "feat: tout\n\nCo-authored-by: Claude <noreply@anthropic.com>",
		AuthorName: "Alice Martin",
		Files: []provider.CommitFile{
			{Path: "main.go", Additions: 120, Deletions: 4},
			{Path: "main_test.go", Additions: 40},
			{Path: "go.sum", Additions: 300, Deletions: 10},
			{Path: "logo.png", Binary: true},
			{Path: "CLAUDE.md", Additions: 12},
		},
	}
	got, ok := Compute(in, ex)
	want := Signals{FilesKept: 3, FilesExcluded: 2, AdditionsKept: 172, DeletionsKept: 4,
		Tools: []string{"D1:claude"}, AgentConfig: true}
	if !ok || got.FilesKept != want.FilesKept || got.FilesExcluded != want.FilesExcluded ||
		got.AdditionsKept != want.AdditionsKept || got.DeletionsKept != want.DeletionsKept ||
		!slices.Equal(got.Tools, want.Tools) || got.AgentConfig != want.AgentConfig || got.BotAuthor {
		t.Errorf("Compute = %+v, %v; want %+v", got, ok, want)
	}

	// Unknown file detail: no value invented.
	if _, ok := Compute(Input{Message: "x"}, ex); ok {
		t.Error("Compute without file detail: ok")
	}
	// Empty commit: known, all zero.
	if s, ok := Compute(Input{Files: []provider.CommitFile{}}, ex); !ok || s.FilesKept != 0 || s.Tools == nil {
		t.Errorf("empty commit: %+v, %v", s, ok)
	}
}

