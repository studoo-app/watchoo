func TestExcluder(t *testing.T) {
	ex, err := NewExcluder(DefaultExclude)
	if err != nil {
		t.Fatal(err)
	}
	for p, want := range map[string]bool{
		"package-lock.json":          true,
		"web/package-lock.json":      true,
		"go.sum":                     true,
		"vendor/lib/a.go":            true,
		"api/vendor/lib/a.go":        true,
		"node_modules/x/index.js":    true,
		"api/gen/user.pb.go":         true,
		"models_generated.go":        true,
		"static/app.min.js":          true,
		"dist/app.js":                true,
		"src/__snapshots__/a.snap":   true,
		"main.go":                    false,
		"vendors.go":                 false, // not the vendor/ directory
		"src/distance.go":            false, // not the dist/ directory
		"internal/build.go":          false, // a file, not the build/ directory
		"docs/package-lock.json.txt": false,
	} {
		if got := ex.Excluded(p); got != want {
			t.Errorf("Excluded(%q) = %v, want %v", p, got, want)
		}
	}

	full, err := NewExcluder([]string{"web/static/*.js", "a/b/"})
	if err != nil {
		t.Fatal(err)
	}
	for p, want := range map[string]bool{
		"web/static/app.js":     true,
		"web/static/sub/app.js": false, // path.Match: "*" does not cross "/"
		"other/web/static/a.js": false, // full path pattern: anchored at the root
		"a/b/c.txt":             true,
		"x/a/b/c.txt":           true,
		"a/bc/d.txt":            false,
	} {
		if got := full.Excluded(p); got != want {
			t.Errorf("Excluded(%q) = %v, want %v", p, got, want)
		}
	}

	var none *Excluder
	if none.Excluded("vendor/a.go") {
		t.Error("nil Excluder excludes a file")
	}
	for _, bad := range []string{"", "  ", "[", "a/["} {
		if _, err := NewExcluder([]string{bad}); err == nil {
			t.Errorf("NewExcluder(%q): no error", bad)
		}
	}
}

func TestDeclaredTools(t *testing.T) {
	for _, tc := range []struct {
		name, msg string
		want      []string
	}{
		{"none", "feat: ajoute la page\n\nCorps du message.", []string{}},
		{"claude trailer", "feat: x\n\nCo-authored-by: Claude <noreply@anthropic.com>", []string{ToolClaude}},
		{"claude model name", "fix: y\n\nCo-authored-by: Claude Opus <noreply@anthropic.com>\n", []string{ToolClaude}},
		{"copilot trailer, lower case key", "fix\n\nco-authored-by: Copilot <copilot@github.com>", []string{ToolCopilot}},
		{"codex trailer", "x\n\nCo-authored-by: Codex Agent <noreply@openai.com>", []string{ToolCodex}},
		{"cursor trailer", "x\n\nCo-authored-by: Cursor Agent <cursoragent@cursor.com>", []string{ToolCursor}},
		{"human co-author", "x\n\nCo-authored-by: Bob Martin <bob@example.test>", []string{}},
		{"claude signature", "x\n\n🤖 Generated with [Claude Code](https://claude.com/claude-code)", []string{ToolClaude, ToolUnnamed}},
		{"codex signature", "x\n\nGenerated by Codex", []string{ToolCodex}},
		{"two tools, CRLF", "x\r\n\r\nCo-authored-by: Codex <noreply@openai.com>\r\nCo-authored-by: Claude <noreply@anthropic.com>\r\n",
			[]string{ToolClaude, ToolCodex}},
		{"duplicate", "x\n\nCo-authored-by: Claude <noreply@anthropic.com>\nGenerated with Claude Code", []string{ToolClaude}},
		{"word in the subject is not a trailer", "docs: compare claude and copilot", []string{}},
	} {
		if got := DeclaredTools(tc.msg); !slices.Equal(got, tc.want) || got == nil {
			t.Errorf("%s: DeclaredTools = %#v, want %#v", tc.name, got, tc.want)
		}
	}
}

func TestCompute(t *testing.T) {
	ex, err := NewExcluder(DefaultExclude)
	if err != nil {
		t.Fatal(err)
	}
	in := Input{
		Message:    "feat: tout\n\nCo-authored-by: Claude <noreply@anthropic.com>",
		AuthorName: "Alice Martin",
		Files: []provider.CommitFile{
			{Path: "main.go", Additions: 120, Deletions: 4},
			{Path: "main_test.go", Additions: 40},
			{Path: "go.sum", Additions: 300, Deletions: 10},
			{Path: "logo.png", Binary: true},
			{Path: "CLAUDE.md", Additions: 12},
		},
	}
	got, ok := Compute(in, ex)
	want := Signals{FilesKept: 3, FilesExcluded: 2, AdditionsKept: 172, DeletionsKept: 4,
		Tools: []string{ToolClaude}, AgentConfig: true}
	if !ok || got.FilesKept != want.FilesKept || got.FilesExcluded != want.FilesExcluded ||
		got.AdditionsKept != want.AdditionsKept || got.DeletionsKept != want.DeletionsKept ||
		!slices.Equal(got.Tools, want.Tools) || got.AgentConfig != want.AgentConfig || got.BotAuthor {
		t.Errorf("Compute = %+v, %v; want %+v", got, ok, want)
	}

	// Unknown file detail: no value invented.
	if _, ok := Compute(Input{Message: "x"}, ex); ok {
		t.Error("Compute without file detail: ok")
	}
	// Empty commit: known, all zero.
	if s, ok := Compute(Input{Files: []provider.CommitFile{}}, ex); !ok || s.FilesKept != 0 || s.Tools == nil {
		t.Errorf("empty commit: %+v, %v", s, ok)
	}
}

func TestBotAndAgentConfig(t *testing.T) {
	for name, want := range map[string]bool{
		"dependabot[bot]":   true,
		"Copilot[BOT]":      true,
		"copilot-swe-agent": true,
		"Alice":             false,
		"":                  false,
		"robot":             false,
	} {
		if got := isBot(name); got != want {
			t.Errorf("isBot(%q) = %v, want %v", name, got, want)
		}
	}
	if s, _ := Compute(Input{AuthorLogin: "renovate[bot]", Files: []provider.CommitFile{}}, nil); !s.BotAuthor {
		t.Error("bot login not detected")
	}
	for p, want := range map[string]bool{
		"AGENTS.md":                       true,
		"docs/CLAUDE.md":                  true,
		".cursorrules":                    true,
		".cursor/rules/go.mdc":            true,
		".github/copilot-instructions.md": true,
		".aider.conf.yml":                 true,
		".windsurfrules":                  true,
		"README.md":                       false,
		"claude.md":                       false, // case kept: the tools use these exact names
		"src/cursor.go":                   false,
		"docs/copilot-instructions.md":    false,
	} {
		if got := isAgentConfig(p); got != want {
			t.Errorf("isAgentConfig(%q) = %v, want %v", p, got, want)
		}
	}
}
