func TestExcluder(t *testing.T) {
	ex, err := NewExcluder(DefaultExclude)
	if err != nil {
		t.Fatal(err)
	}
	for p, want := range map[string]bool{
		"package-lock.json":          true,
		"web/package-lock.json":      true,
		"go.sum":                     true,
		"vendor/lib/a.go":            true,
		"api/vendor/lib/a.go":        true,
		"node_modules/x/index.js":    true,
		"api/gen/user.pb.go":         true,
		"models_generated.go":        true,
		"static/app.min.js":          true,
		"dist/app.js":                true,
		"src/__snapshots__/a.snap":   true,
		"main.go":                    false,
		"vendors.go":                 false, // not the vendor/ directory
		"src/distance.go":            false, // not the dist/ directory
		"internal/build.go":          false, // a file, not the build/ directory
		"docs/package-lock.json.txt": false,
	} {
		if got := ex.Excluded(p); got != want {
			t.Errorf("Excluded(%q) = %v, want %v", p, got, want)
		}
	}

	full, err := NewExcluder([]string{"web/static/*.js", "a/b/"})
	if err != nil {
		t.Fatal(err)
	}
	for p, want := range map[string]bool{
		"web/static/app.js":     true,
		"web/static/sub/app.js": false, // path.Match: "*" does not cross "/"
		"other/web/static/a.js": false, // full path pattern: anchored at the root
		"a/b/c.txt":             true,
		"x/a/b/c.txt":           true,
		"a/bc/d.txt":            false,
	} {
		if got := full.Excluded(p); got != want {
			t.Errorf("Excluded(%q) = %v, want %v", p, got, want)
		}
	}

	forms, err := NewExcluder([]string{"*.egg-info/", "/build/", "/go.sum", "gen/out/"})
	if err != nil {
		t.Fatal(err)
	}
	for p, want := range map[string]bool{
		"pkg.egg-info/PKG-INFO": true, // glob in a directory pattern
		"a/pkg.egg-info/x":      true,
		"build/out.js":          true,  // root directory
		"web/build/out.js":      false, // "/build/": root only
		"go.sum":                true,  // "/go.sum": file at the root
		"tools/go.sum":          false,
		"gen/out/a.go":          true,
		"src/gen/out/a.go":      true,
		"gen/output/a.go":       false,
		"pkg.egg-info":          false, // a file, not a directory
	} {
		if got := forms.Excluded(p); got != want {
			t.Errorf("Excluded(%q) = %v, want %v", p, got, want)
		}
	}

	var none *Excluder
	if none.Excluded("vendor/a.go") {
		t.Error("nil Excluder excludes a file")
	}
	for _, bad := range []string{"", "  ", "[", "a/[", "/", "a//b", "[x/"} {
		if _, err := NewExcluder([]string{bad}); err == nil {
			t.Errorf("NewExcluder(%q): no error", bad)
		}
	}
}

func TestMessageDeclarations(t *testing.T) {
	d1 := func(tool string) Declaration { return Declaration{Signal: SignalCoAuthor, Tool: tool} }
	d2 := func(tool string) Declaration { return Declaration{Signal: SignalSignature, Tool: tool} }
	for _, tc := range []struct {
		name, msg string
		want      []Declaration
	}{
		{"none", "feat: ajoute la page\n\nCorps du message.", []Declaration{}},
		{"claude trailer", "feat: x\n\nCo-authored-by: Claude <noreply@anthropic.com>", []Declaration{d1(ToolClaude)}},
		{"claude model name", "fix: y\n\nCo-authored-by: Claude Opus <noreply@anthropic.com>\n", []Declaration{d1(ToolClaude)}},
		{"copilot trailer, lower case key", "fix\n\nco-authored-by: Copilot <copilot@github.com>", []Declaration{d1(ToolCopilot)}},
		{"codex trailer", "x\n\nCo-authored-by: Codex Agent <noreply@openai.com>", []Declaration{d1(ToolCodex)}},
		{"cursor trailer", "x\n\nCo-authored-by: Cursor Agent <cursoragent@cursor.com>", []Declaration{d1(ToolCursor)}},
		{"human co-author", "x\n\nCo-authored-by: Bob Martin <bob@example.test>", []Declaration{}},
		{"classmate named Claude", "x\n\nCo-authored-by: Claude Martin <claude.martin@ecole.example>", []Declaration{}},
		{"claude signature", "x\n\n🤖 Generated with [Claude Code](https://claude.com/claude-code)",
			[]Declaration{d2(ToolClaude), d2(ToolUnnamed)}},
		{"codex signature", "x\n\nGenerated by Codex", []Declaration{d2(ToolCodex)}},
		{"two tools, CRLF", "x\r\n\r\nCo-authored-by: Codex <noreply@openai.com>\r\nCo-authored-by: Claude <noreply@anthropic.com>\r\n",
			[]Declaration{d1(ToolClaude), d1(ToolCodex)}},
		{"trailer and signature", "x\n\nCo-authored-by: Claude <noreply@anthropic.com>\nGenerated with Claude Code",
			[]Declaration{d1(ToolClaude), d2(ToolClaude)}},
		{"word in the subject is not a trailer", "docs: compare claude and copilot", []Declaration{}},
	} {
		if got := MessageDeclarations(tc.msg); !slices.Equal(got, tc.want) || got == nil {
			t.Errorf("%s: MessageDeclarations = %#v, want %#v", tc.name, got, tc.want)
		}
	}
}

func TestPullRequestDeclarationsAndBranches(t *testing.T) {
	body := "Résumé\n\n🤖 Generated with [Claude Code](https://claude.com/claude-code)\n\nCo-authored-by: Codex <noreply@openai.com>"
	want := []Declaration{{SignalSignature, ToolClaude}, {SignalSignature, ToolCodex}, {SignalSignature, ToolUnnamed}}
	if got := PullRequestDeclarations(body); !slices.Equal(got, want) {
		t.Errorf("PullRequestDeclarations = %v, want %v", got, want)
	}
	if got := PullRequestDeclarations(""); got == nil || len(got) != 0 {
		t.Errorf("empty body: %#v", got)
	}
	for branch, want := range map[string]string{
		"codex/fix-login": ToolCodex, "copilot/issue-12": ToolCopilot, "claude/refacto": ToolClaude,
		"cursor/x": ToolCursor, "codex/": "", "feature/codex": "", "main": "", "Claude/x": "",
	} {
		tool, ok := AgentBranch(branch)
		if tool != want || ok != (want != "") {
			t.Errorf("AgentBranch(%q) = %q, %v; want %q", branch, tool, ok, want)
		}
	}
}

func TestEncodeDecodeDeclarations(t *testing.T) {
	ds := []Declaration{{SignalCoAuthor, ToolClaude}, {SignalSignature, ToolUnnamed}}
	enc := EncodeDeclarations(ds)
	if !slices.Equal(enc, []string{"D1:claude", "D2:unnamed"}) {
		t.Errorf("EncodeDeclarations = %v", enc)
	}
	if got := DecodeDeclarations(append(enc, "", "D1:claude")); !slices.Equal(got, ds) {
		t.Errorf("DecodeDeclarations = %v", got)
	}
	// Early 7.1 form, without signal: attached to D1.
	if got := DecodeDeclarations([]string{"codex"}); !slices.Equal(got, []Declaration{{SignalCoAuthor, ToolCodex}}) {
		t.Errorf("DecodeDeclarations(legacy) = %v", got)
	}
	if got := DecodeDeclarations(nil); got == nil || len(got) != 0 {
		t.Errorf("DecodeDeclarations(nil) = %#v", got)
	}
}

